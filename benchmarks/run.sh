#!/usr/bin/env bash
set -e

# Определение числа ядер процессора
CORES=$(nproc 2>/dev/null || echo 4)

echo "======================================================================"
echo "          Запуск полного научного бенчмарка FractalSNN                "
echo "          Задействовано потоков CPU: ${CORES}                          "
echo "======================================================================"

mkdir -p results

# Компиляция с максимальной оптимизацией O3 и инлайнингом
fpc -O3 -Mobjfpc -S2 -Si -Fu../src run_benchmarks.pas

# Запуск с замером точного времени выполнения
START_TIME=$(date +%s)

./run_benchmarks

END_TIME=$(date +%s)
ELAPSED=$((END_TIME - START_TIME))

rm -f *.o *.ppu

echo "======================================================================"
echo "   [SUCCESS] Бенчмарк завершен за ${ELAPSED} сек."
echo "   Результаты сохранены в benchmarks/results/"
echo "======================================================================"
